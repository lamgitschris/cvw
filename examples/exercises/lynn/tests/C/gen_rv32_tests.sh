emit_test_block_jalr() {
  # args: UPPER i next_label
  local upper="$1" i="$2" next="$3"

  cat <<EOF
    test${i}:
        addi t3, x0, 0          # flag = 0

        # --- Get address of TARGET into t0 without AUIPC/LUI ---
        jal  t0, ${upper}_GET_TGT_${i}
${upper}_GET_TGT_${i}:
        # t0 = PC+4 of the jal above (i.e., address of the next instruction)
        # Now redirect control flow away so we can place TARGET elsewhere.
        jal  x0, ${upper}_DO_JALR_${i}

        # --- This label's address is what we want to jump to ---
${upper}_TARGET_${i}:
        addi t3, x0, 1          # flag = 1 (means we landed)
        jal  x0, ${upper}_CHECK_${i}

${upper}_DO_JALR_${i}:
        # At this point, t0 holds address of the instruction right after the jal to GET_TGT.
        # That instruction is the 'jal x0, DO_JALR' itself, NOT TARGET.
        # So instead, do another jal that *lands near TARGET* and captures its link.

        jal  t0, ${upper}_TGT_LINK_${i}
${upper}_TGT_LINK_${i}:
        # t0 = PC+4 here, and we are positioned immediately before TARGET via fall-through.
        # Place TARGET immediately next so t0 == address of TARGET.
        jal  x0, ${upper}_TARGET_${i}

        # (control never reaches here)

${upper}_CHECK_${i}:
        # flag must be 1
        addi t4, x0, 1
        beq  t3, t4, ${next}
        jal  x0, Fail_${upper}_${i}

EOF
}

