emit_test_block_store_word() {
  # args: OP UPPER i BASE_ADDR_UNUSED WORD_HEX BYTE_OFF STORE_VAL next
  local op="$1" upper="$2" i="$3" _base="$4" word_hex="$5" boff="$6" sval="$7" next="$8"

  # parse initial bytes (memory order)
  local b0 b1 b2 b3
  read -r b0 b1 b2 b3 <<<"$word_hex"

  # compute expected bytes after store (in bash)
  local eb0="$b0" eb1="$b1" eb2="$b2" eb3="$b3"

  if [[ "$op" == "sb" ]]; then
    local v=$((sval & 0xFF))
    local vhex; printf -v vhex "%02x" "$v"
    case "$boff" in
      0) eb0="$vhex" ;;
      1) eb1="$vhex" ;;
      2) eb2="$vhex" ;;
      3) eb3="$vhex" ;;
      *) echo "bad boff sb: $boff" >&2; exit 1 ;;
    esac
  else # sh
    local vlo=$((sval & 0xFF))
    local vhi=$(((sval >> 8) & 0xFF))
    local vlohex vhihex
    printf -v vlohex "%02x" "$vlo"
    printf -v vhihex "%02x" "$vhi"
    case "$boff" in
      0) eb0="$vlohex"; eb1="$vhihex" ;;
      2) eb2="$vlohex"; eb3="$vhihex" ;;
      *) echo "bad boff sh: $boff" >&2; exit 1 ;;
    esac
  fi

  # store value bytes for scratch->lw
  local sv0=$((sval & 0xFF))
  local sv1=$(((sval >> 8) & 0xFF))

  cat <<EOF
    test${i}:
        addi sp, sp, -12
        addi t0, sp, 0      # target word   @ sp+0
        addi t2, sp, 4      # expected word @ sp+4
        addi t3, sp, 8      # scratch       @ sp+8

        # init target bytes
        addi t1, x0, 0x${b0}; sb t1, 0(t0)
        addi t1, x0, 0x${b1}; sb t1, 1(t0)
        addi t1, x0, 0x${b2}; sb t1, 2(t0)
        addi t1, x0, 0x${b3}; sb t1, 3(t0)

        # init expected bytes
        addi t1, x0, 0x${eb0}; sb t1, 0(t2)
        addi t1, x0, 0x${eb1}; sb t1, 1(t2)
        addi t1, x0, 0x${eb2}; sb t1, 2(t2)
        addi t1, x0, 0x${eb3}; sb t1, 3(t2)

        # build store value in t1 via scratch bytes then lw
        addi t1, x0, ${sv0}; sb t1, 0(t3)
        addi t1, x0, ${sv1}; sb t1, 1(t3)
        addi t1, x0, 0;      sb t1, 2(t3)
        addi t1, x0, 0;      sb t1, 3(t3)
        lw   t1, 0(t3)

        # perform store into target
        ${op} t1, ${boff}(t0)

        # compare lw(target) vs lw(expected)
        lw   t4, 0(t0)
        lw   t5, 0(t2)
        beq  t4, t5, 1f
        jal  x0, Fail_${upper}_${i}
1:
        addi sp, sp, 12
        jal  x0, ${next}

EOF
}

