gen_lui_file() {
  # args: name upper base_gp vectors_array_name
  local name="$1" upper="$2" base_gp="$3" vectors_name="$4"
  LIT_POOL=""
  local -n VEC="$vectors_name"

  emit_header "$name"

  local i=1
  for imm in "${VEC[@]}"; do
    local next="test$((i+1))"; [[ "$i" -eq 10 ]] && next="pass"
    emit_test_block_lui "$upper" "$i" "$imm" "$next"
    i=$((i+1))
  done

  cat <<EOF
    pass:
        jal  x0, return_${name}_test
EOF

  if [[ -n "$LIT_POOL" ]]; then
    cat <<EOF

    # ---- literal pool (auto-generated) ----
$LIT_POOL
EOF
  fi

  emit_fail_footer "$upper" "$base_gp"
}

