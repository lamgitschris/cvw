  "-1 -1"     # 0xFFFFFFFF < 0xFFFFFFFF => 0
  "-1 0"      # 0xFFFFFFFF < 0 => 0
  "2047 2047" # equal => 0
  "2046 2047" # 2046 < 2047 => 1
  "0 -2048"   # 0 < 0xFFFFF800 => 1 (unsigned)
  "-2048 -2048" # equal => 0
)

