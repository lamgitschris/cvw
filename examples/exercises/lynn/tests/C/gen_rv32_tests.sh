emit_load_expected_into_t3() {
  local exp_s="$1"
  local exp_hex="$2"

  if fits_imm12 "$exp_s"; then
    cat <<EOF
        addi t3, x0, $exp_s
EOF
  else
    local u=$(( exp_s & 0xffffffff ))
    local hi=$(( (u + 0x800) >> 12 ))
    local lo=$(( u - (hi << 12) ))

    # HARD GUARANTEE lo fits imm12
    if ! fits_imm12 "$lo"; then
      echo "FATAL: lo out of range in emit_load_expected_into_t3: $lo" >&2
      exit 1
    fi

    cat <<EOF
        lui  t3, $hi
        addi t3, t3, $lo
EOF
  fi
}

# Load an arbitrary 32-bit signed constant into rd using only:
#   addi (if fits imm12) OR jal+addi+lw from literal pool.
# Uses the same LIT_POOL mechanism as expected-value loading.
emit_load_const() {
  local rd="$1"
  local val="$2"

  read -r val_s val_hex < <(python3 - "$val" <<'PY'
import sys
x = int(sys.argv[1], 0)
u = x & 0xFFFFFFFF
s = u if u < 0x80000000 else u - 0x100000000
print(s, f"0x{u:08x}")
PY
)

  if fits_imm12 "$val_s"; then
    cat <<EOF
        addi ${rd}, x0, ${val_s}
EOF
  else
    local u=$(( val_s & 0xffffffff ))
    local hi=$(( (u + 0x800) >> 12 ))
    local lo=$(( u - (hi << 12) ))

    # HARD GUARANTEE lo fits imm12
    if ! fits_imm12 "$lo"; then
      echo "FATAL: lo out of range in emit_load_const: $lo" >&2
      exit 1
    fi

    cat <<EOF
        lui  ${rd}, $hi
        addi ${rd}, ${rd}, $lo
EOF
  fi
}

