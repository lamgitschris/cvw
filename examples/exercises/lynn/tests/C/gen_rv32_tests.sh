# -----------------------------
# Input vectors (inputs only!)
# Each entry: "rs1 shamt"
# Script computes expected RV32 result automatically.
# Include shamt-masking edge cases: 32->0, 33->1, 63->31, etc.
# -----------------------------

SRL_INPUTS=(
  "8 1"             # 8 >> 1 = 4
  "7 2"             # 7 >> 2 = 1
  "-1 1"            # 0xFFFFFFFF >> 1 = 0x7FFFFFFF
  "-2147483648 1"   # 0x80000000 >> 1 = 0x40000000
  "1 0"             # shift by 0
  "1024 5"          # 1024 >> 5 = 32
  "1 31"            # 1 >> 31 = 0
  "-2 1"            # 0xFFFFFFFE >> 1 = 0x7FFFFFFF
  "1 32"            # masked shamt (32->0)
  "1 33"            # masked shamt (33->1)
)

SRLI_INPUTS=(
  "8 1"
  "7 2"
  "-1 1"
  "-2147483648 1"
  "1 0"
  "1024 5"
  "1 31"
  "-2 1"
  "2147483647 30"
  "-2147483648 30"
)

SRA_INPUTS=(
  "-1 1"            # stays -1 with arithmetic shift
  "-2 1"            # -2 >> 1 = -1 (arithmetic)
  "-2147483648 1"   # 0x80000000 >> 1 = 0xC0000000 (sign-extend)
  "-2147483648 31"  # >>31 = -1
  "2147483647 1"    # 0x7FFFFFFF >> 1 = 0x3FFFFFFF
  "16 3"            # 16 >> 3 = 2
  "-16 3"           # -16 >> 3 = -2
  "1 0"             # shift by 0
  "-1 32"           # masked shamt (32->0) => -1
  "-8 33"           # masked shamt (33->1) => -4
)

