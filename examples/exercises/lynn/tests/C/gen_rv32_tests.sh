write_file() {
  local path="$1"
  local tmp="${path}.tmp"

  cat > "$tmp"

  if [[ -f "$path" ]] && cmp -s "$path" "$tmp"; then
    rm "$tmp"
    echo "unchanged: $path"
  else
    mv "$tmp" "$path"
    echo "updated: $path"
  fi
}

emit_autogen_banner() {
  cat <<'EOF'
// AUTO-GENERATED FILE — DO NOT EDIT BY HAND
// Generated by gen_rv32_tests.sh
// Christian LamAlvarez
// clamalvarez@hmc.edu
// 2/11/2026

EOF
}

emit_header() {
  local testname="$1"  # e.g. srl
  emit_autogen_banner
  cat <<EOF
.extern return_${testname}_test
.extern fail

.section .text.init
.globl ${testname}_test
.type  ${testname}_test, @function

${testname}_test:
EOF
}

emit_set_gp_code() {
  local code="$1"

  if [[ "$code" -ge -2048 && "$code" -le 2047 ]]; then
    cat <<EOF
    addi gp, x0, ${code}
EOF
    return
  fi

  local base=2047
  local rem=$((code - base))

  # For your use (<= ~2600), this always fits imm12.
  cat <<EOF
    addi gp, x0, ${base}
    addi gp, gp, ${rem}
EOF
}

emit_fail_footer() {
  local upper="$1"
  local base_gp="$2"
  for i in $(seq 1 10); do
    local code=$((base_gp + i))
    cat <<EOF

Fail_${upper}_${i}:
$(emit_set_gp_code "$code")
    jal  x0, fail
EOF
  done
}

# EXPECTED RESULT FUNCTIONS
# -----------------------------
# EXPECTED RESULT: SHIFTS (RV32)
# Supported ops: sll/slli/srl/srli/sra/srai
# Returns: "<signed_expected> <hex_u32>"
# -----------------------------
rv32_expect_shift() {
  # args: OP RS1 SHAMT
  python3 - "$1" "$2" "$3" <<'PY'
import sys

op = sys.argv[1]
rs1 = int(sys.argv[2], 0)
shamt_in = int(sys.argv[3], 0)

def to_u32(x):
    return x & 0xFFFFFFFF

def to_s32(u):
    u &= 0xFFFFFFFF
    return u if u < 0x80000000 else u - 0x100000000

shamt = shamt_in & 0x1F  # RV32 uses low 5 bits
u = to_u32(rs1)

if op in ("sll", "slli"):
    res_u = to_u32(u << shamt)
elif op in ("srl", "srli"):
    res_u = (u >> shamt)  # logical shift right
elif op in ("sra", "srai"):
    s = to_s32(u)          # arithmetic shift right
    res_u = to_u32(s >> shamt)
else:
    raise SystemExit(f"unsupported shift op: {op}")

res_s = to_s32(res_u)
print(res_s, f"0x{res_u:08x}")
PY
}

# ----------------------------------------
# EXPECTED RESULT: UNSIGNED COMPARES (RV32)
# Supported ops: sltu, sltiu
# sltu:  unsigned(rs1) < unsigned(rs2)
# sltiu: unsigned(rs1) < unsigned(signext(imm12))
# Returns: "0" or "1"
# ----------------------------------------
rv32_expect_ucmp() {
  # args: OP RS1 RHS   (RHS is RS2 for sltu, IMM12 for sltiu)
  python3 - "$1" "$2" "$3" <<'PY'
import sys

op = sys.argv[1]
rs1 = int(sys.argv[2], 0)
rhs = int(sys.argv[3], 0)

def to_u32(x):
    return x & 0xFFFFFFFF

def signext_imm12(x):
    x &= 0xFFF
    return x if x < 0x800 else x - 0x1000

a = to_u32(rs1)

if op == "sltu":
    b = to_u32(rhs)
elif op == "sltiu":
    b = to_u32(signext_imm12(rhs))
else:
    raise SystemExit(f"unsupported ucmp op: {op}")

print(1 if a < b else 0)
PY
}

fits_imm12() {
  local x="$1"
  [[ "$x" -ge -2048 && "$x" -le 2047 ]]
}

# ----------------------------------------
# EXPECTED RESULT: LOADS (RV32, little-endian)
# Supported ops: lb, lbu, lh, lhu
# Memory is provided as hex bytes: e.g. "00 ff 7f 80 ..."
# offset is a byte offset into that byte array
# Returns: "<signed_expected> <hex_u32>"
# ----------------------------------------
rv32_expect_load() {
  # args: OP "HEX_BYTES" OFFSET
  python3 - "$1" "$2" "$3" <<'PY'
import sys

op = sys.argv[1]
hex_bytes = sys.argv[2]
off = int(sys.argv[3])

# parse bytes like: "00 ff 7f 80"
mem = bytes(int(b, 16) for b in hex_bytes.split())

def to_u32(x): return x & 0xFFFFFFFF
def to_s32(u):
    u &= 0xFFFFFFFF
    return u if u < 0x80000000 else u - 0x100000000

def signext(val, bits):
    sign = 1 << (bits - 1)
    mask = (1 << bits) - 1
    val &= mask
    return val - (1 << bits) if (val & sign) else val

if op in ("lb", "lbu"):
    b = mem[off]
    if op == "lb":
        v = signext(b, 8)
    else:
        v = b
elif op in ("lh", "lhu"):
    # little-endian halfword
    b0 = mem[off]
    b1 = mem[off + 1]
    hw = b0 | (b1 << 8)
    if op == "lh":
        v = signext(hw, 16)
    else:
        v = hw
else:
    raise SystemExit(f"unsupported load op: {op}")

res_u = to_u32(v)
print(to_s32(res_u), f"0x{res_u:08x}")
PY
}

# ----------------------------------------
# EXPECTED RESULT: STORES (RV32, little-endian)
# Supported ops: sb, sh
# Given an initial 32-bit word (4 bytes) as hex bytes, applies the store at byte offset,
# and returns expected full 32-bit word after the store:
# Returns: "<signed_expected> <hex_u32>"
# ----------------------------------------
rv32_expect_store_word() {
  # args: OP "WORD_HEX_BYTES" BYTE_OFFSET STORE_VAL
  # WORD_HEX_BYTES example: "aa bb cc dd" (4 bytes, little-endian in memory)
  python3 - "$1" "$2" "$3" "$4" <<'PY'
import sys

op = sys.argv[1]
word_hex = sys.argv[2]
byte_off = int(sys.argv[3])
store_val = int(sys.argv[4])

bs = [int(b,16) for b in word_hex.split()]
if len(bs) != 4:
    raise SystemExit("WORD_HEX_BYTES must be exactly 4 bytes")

def to_u32(x): return x & 0xFFFFFFFF
def to_s32(u):
    u &= 0xFFFFFFFF
    return u if u < 0x80000000 else u - 0x100000000

# apply store into the 4-byte array
if op == "sb":
    bs[byte_off] = store_val & 0xFF
elif op == "sh":
    # writes 2 bytes little-endian; expect byte_off 0 or 2 (aligned halfword in word)
    bs[byte_off]     = store_val & 0xFF
    bs[byte_off + 1] = (store_val >> 8) & 0xFF
else:
    raise SystemExit(f"unsupported store op: {op}")

u = bs[0] | (bs[1]<<8) | (bs[2]<<16) | (bs[3]<<24)
print(to_s32(u), f"0x{u:08x}")
PY
}

# ----------------------------------------
# EXPECTED RESULT: BRANCHES (RV32)
# Supported ops: bne, blt, bltu, bge, bgeu
# Returns: "0" (not taken) or "1" (taken)
# ----------------------------------------
rv32_expect_branch() {
  # args: OP RS1 RS2
  python3 - "$1" "$2" "$3" <<'PY'
import sys

op = sys.argv[1]
rs1 = int(sys.argv[2], 0)
rs2 = int(sys.argv[3], 0)

def to_u32(x): return x & 0xFFFFFFFF
def to_s32(u):
    u &= 0xFFFFFFFF
    return u if u < 0x80000000 else u - 0x100000000

a_u = to_u32(rs1)
b_u = to_u32(rs2)
a_s = to_s32(a_u)
b_s = to_s32(b_u)

take = 0
if op == "bne":
    take = 1 if a_u != b_u else 0
elif op == "blt":
    take = 1 if a_s < b_s else 0
elif op == "bltu":
    take = 1 if a_u < b_u else 0
elif op == "bge":
    take = 1 if a_s >= b_s else 0
elif op == "bgeu":
    take = 1 if a_u >= b_u else 0
else:
    raise SystemExit(f"unsupported branch op: {op}")

print(take)
PY
}

# ----------------------------------------
# EXPECTED RESULT: U-TYPE UPPER (RV32)
# Used for: lui, auipc (imm20 << 12)
# Accepts signed/unsigned imm in assembly form; masks to 20 bits.
# Returns: "<signed_expected> <hex_u32>"
# ----------------------------------------
rv32_expect_u_upper() {
  # args: IMM20
  python3 - "$1" <<'PY'
import sys
imm = int(sys.argv[1], 0)

def to_u32(x): return x & 0xFFFFFFFF
def to_s32(u):
    u &= 0xFFFFFFFF
    return u if u < 0x80000000 else u - 0x100000000

imm20 = imm & 0xFFFFF
u = to_u32(imm20 << 12)
print(to_s32(u), f"0x{u:08x}")
PY
}

