  emit_fail_footer "$upper" "$base_gp"

  cat <<EOF

.section .data
.org 0x1100
.align 2
EOF

  local i2=1
  for v in "${VEC[@]}"; do
    IFS='|' read -r _ whex _ _ <<<"$v"
    cat <<EOF
