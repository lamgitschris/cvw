#!/usr/bin/env bash
set -euo pipefail

# Usage:
#   ./gen_pipeline_tests.sh [OUTDIR]
#   FORCE=1 ./gen_pipeline_tests.sh [OUTDIR]
#
# Generates two categories of pipeline tests targeting riscvpipe:
#   1. Hazard-safe (NOP-padded) — validates pipeline structure, no hazard unit needed
#   2. Hazard-specific — requires forwarding/stall/flush to produce correct results
#
# Pipeline context (riscvpipe):
#   - 5-stage: IF -> ID -> EX -> MEM -> WB
#   - Branches resolved in EX (2-cycle flush penalty on taken)
#   - Load-use stall: 1-cycle bubble injected via FlushE
#   - Forwarding: EX gets MEM result (ForwardAE/BE=10) or WB result (ForwardAE/BE=01)
#   - PCSrcE = (BranchE & BranchOpE) | JumpE flushes IF/ID and ID/EX
#
# Christian LamAlvarez
# clamalvarez@hmc.edu

OUTDIR="${1:-./pipeline_tests}"
FORCE="${FORCE:-0}"

mkdir -p "$OUTDIR"

# ============================================================
# UTILITIES
# ============================================================

die()        { echo "error: $*" >&2; exit 1; }

write_file() {
  local path="$1"
  local tmp="${path}.tmp"
  cat > "$tmp"
  if [[ -f "$path" ]] && cmp -s "$path" "$tmp"; then
    rm "$tmp";  echo "unchanged: $path"
  else
    mv "$tmp" "$path"; echo "updated:   $path"
  fi
}

emit_autogen_banner() {
  cat <<'EOF'
// AUTO-GENERATED FILE — DO NOT EDIT BY HAND
// Generated by gen_pipeline_tests.sh
// Christian LamAlvarez
// clamalvarez@hmc.edu

EOF
}

emit_header() {
  local testname="$1"
  emit_autogen_banner
  cat <<EOF
.extern return_${testname}_test
.extern fail

.section .text.init
.globl ${testname}_test
.type  ${testname}_test, @function

${testname}_test:
EOF
}

# RV32I canonical NOP = addi x0, x0, 0
# n=3 clears the full pipeline between a write and a dependent read
emit_nops() {
  local n="$1"
  for _ in $(seq 1 "$n"); do
    echo "        addi x0, x0, 0"
  done
}

emit_fail_footer() {
  local upper="$1" base_gp="$2"
  for i in $(seq 1 10); do
    local code=$((base_gp + i))
    cat <<EOF

Fail_${upper}_${i}:
        addi gp, x0, ${code}
        jal  x0, fail
EOF
  done
}

fits_imm12() { [[ "$1" -ge -2048 && "$1" -le 2047 ]]; }

# Load a 32-bit signed constant into rd.
# Uses addi if it fits, otherwise lui+addi.
emit_load_const() {
  local rd="$1" val="$2"
  read -r val_s val_hex < <(python3 - "$val" <<'PY'
import sys
x = int(sys.argv[1], 0)
u = x & 0xFFFFFFFF
s = u if u < 0x80000000 else u - 0x100000000
print(s, f"0x{u:08x}")
PY
)
  if fits_imm12 "$val_s"; then
    echo "        addi ${rd}, x0, ${val_s}"
  else
    local u=$(( val_s & 0xffffffff ))
    local hi=$(( (u + 0x800) >> 12 ))
    local lo=$(( u - (hi << 12) ))
    fits_imm12 "$lo" || die "lo out of range in emit_load_const: $lo"
    cat <<EOF
        lui  ${rd}, ${hi}
        addi ${rd}, ${rd}, ${lo}
EOF
  fi
}

# Load expected value into t3 (same contract as gen_rv32_tests.sh)
emit_load_expected_into_t3() {
  local exp_s="$1" exp_hex="$2"
  emit_load_const t3 "$exp_s"
}

# ============================================================
# EXPECTED RESULT HELPERS  (reused from gen_rv32_tests.sh)
# ============================================================

rv32_expect_alu() {
  python3 - "$1" "$2" "$3" <<'PY'
import sys
op  = sys.argv[1]
a   = int(sys.argv[2], 0)
b   = int(sys.argv[3], 0)

def u32(x): return x & 0xFFFFFFFF
def s32(u):
    u &= 0xFFFFFFFF
    return u if u < 0x80000000 else u - 0x100000000

au, bu = u32(a), u32(b)
as_, bs_ = s32(au), s32(bu)

ops = {
  "add":  u32(au + bu),
  "sub":  u32(au - bu),
  "and":  u32(au & bu),
  "or":   u32(au | bu),
  "xor":  u32(au ^ bu),
  "slt":  1 if as_ < bs_ else 0,
  "sltu": 1 if au < bu  else 0,
  "sll":  u32(au << (bu & 0x1f)),
  "srl":  au >> (bu & 0x1f),
  "sra":  u32(as_ >> (bu & 0x1f)),
  "addi": u32(au + bu),
  "andi": u32(au & bu),
  "ori":  u32(au | bu),
  "xori": u32(au ^ bu),
  "slti": 1 if as_ < bs_ else 0,
  "mul":  u32(au * bu),
  "mulh": u32((as_ * bs_) >> 32),
  "mulhu":u32((au * bu)  >> 32),
  "mulhsu": u32((as_ * bu) >> 32),
}
res = ops[op]
res_u = u32(res)
res_s = s32(res_u)
print(res_s, f"0x{res_u:08x}")
PY
}

rv32_expect_branch() {
  python3 - "$1" "$2" "$3" <<'PY'
import sys
op, rs1, rs2 = sys.argv[1], int(sys.argv[2],0), int(sys.argv[3],0)
def u32(x): return x & 0xFFFFFFFF
def s32(u): u&=0xFFFFFFFF; return u if u<0x80000000 else u-0x100000000
au,bu=u32(rs1),u32(rs2); as_,bs_=s32(au),s32(bu)
r={"beq":au==bu,"bne":au!=bu,"blt":as_<bs_,"bge":as_>=bs_,
   "bltu":au<bu,"bgeu":au>=bu}[op]
print(1 if r else 0)
PY
}

# ============================================================
# CATEGORY 1 — HAZARD-SAFE (NOP-padded)
# 3 NOPs between every write and dependent read.
# Should pass on bare pipeline with no hazard unit.
# ============================================================

# Generic ALU block (R-type or I-type, two register operands)
# args: upper i op rs1_val rs2_val next
emit_nop_alu_block() {
  local upper="$1" i="$2" op="$3" rs1="$4" rs2="$5" next="$6"
  read -r exp_s exp_hex < <(rv32_expect_alu "$op" "$rs1" "$rs2")
  cat <<EOF
    test${i}:
EOF
  emit_load_const t0 "$rs1"
  emit_load_const t1 "$rs2"
  cat <<EOF
        ${op}  t2, t0, t1
EOF
  emit_nops 3
  emit_load_expected_into_t3 "$exp_s" "$exp_hex"
  cat <<EOF
        beq  t2, t3, ${next}
        jal  x0, Fail_${upper}_${i}

EOF
}

# NOP-padded load/store roundtrip block
# args: upper i store_val next
emit_nop_load_store_block() {
  local upper="$1" i="$2" val="$3" next="$4"
  read -r val_s _ < <(python3 - "$val" <<'PY'
import sys; x=int(sys.argv[1],0); u=x&0xFFFFFFFF
print(u if u<0x80000000 else u-0x100000000, f"0x{u:08x}")
PY
)
  cat <<EOF
    test${i}:
        addi sp, sp, -4
EOF
  emit_load_const t0 "$val_s"
  cat <<EOF
        sw   t0, 0(sp)
EOF
  emit_nops 3
  cat <<EOF
        lw   t2, 0(sp)
EOF
  emit_nops 3
  emit_load_expected_into_t3 "$val_s" ""
  cat <<EOF
        beq  t2, t3, ${next}
        jal  x0, Fail_${upper}_${i}
        addi sp, sp, 4

EOF
}

# NOP-padded branch block — branch is not taken (fall-through path verified)
# args: upper i op rs1 rs2 next
emit_nop_branch_block() {
  local upper="$1" i="$2" op="$3" rs1="$4" rs2="$5" next="$6"
  local exp; exp="$(rv32_expect_branch "$op" "$rs1" "$rs2")"
  cat <<EOF
    test${i}:
EOF
  emit_load_const t0 "$rs1"
  emit_load_const t1 "$rs2"
  cat <<EOF
        addi t2, x0, 0
        ${op}  t0, t1, ${upper}_TAKEN_${i}
        jal  x0, ${upper}_AFTER_${i}
${upper}_TAKEN_${i}:
        addi t2, x0, 1
${upper}_AFTER_${i}:
EOF
  emit_nops 3
  cat <<EOF
        addi t3, x0, ${exp}
        beq  t2, t3, ${next}
        jal  x0, Fail_${upper}_${i}

EOF
}

