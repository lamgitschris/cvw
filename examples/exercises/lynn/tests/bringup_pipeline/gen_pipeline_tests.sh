gen_nop_alu_file() {
  local name="NOP_ALU" base_gp=100
  emit_header "nop_alu"
  local vectors=(
    "add  10  20"   "add  -1  1"    "sub  50  30"   "sub  -2048 1"
    "and  0xFF 0x0F" "or  0xF0 0x0F" "xor 0xAA 0x55" "slt  -1  0"
    "sltu 0  -1"    "add  2047 1"
  )
  local i=1
  for v in "${vectors[@]}"; do
    read -r op rs1 rs2 <<<"$v"
    local next="test$((i+1))"; [[ $i -eq 10 ]] && next="pass"
    emit_nop_alu_block "$name" "$i" "$op" "$rs1" "$rs2" "$next"
    i=$((i+1))
  done
  cat <<EOF
    pass:
        jal  x0, return_nop_alu_test
EOF
  emit_fail_footer "$name" "$base_gp"
}

