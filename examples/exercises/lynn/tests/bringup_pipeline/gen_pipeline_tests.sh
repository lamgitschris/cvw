# ============================================================
# CATEGORY 2 — HAZARD-SPECIFIC
# These tests ONLY produce correct results if the hazard unit
# is functioning correctly.
# ============================================================

# --- 2a. EX->EX forwarding (ForwardAE/BE = 2'b10) ---
# Producer is immediately followed by consumer.
# Without EX->EX forward, consumer reads stale register file value.
# args: upper i op rs1_val rs2_val next
emit_raw_ex_ex_block() {
  local upper="$1" i="$2" op="$3" rs1="$4" rs2="$5" next="$6"
  read -r exp_s exp_hex < <(rv32_expect_alu "add" "$rs1" "$rs2")
  cat <<EOF
    test${i}:
EOF
  emit_load_const t0 "$rs1"
  emit_nops 3                          # let t0 settle in WB first
  emit_load_const t1 "$rs2"
  emit_nops 3                          # let t1 settle in WB first
  # Now produce a new value in t0 — next instruction immediately consumes it
  emit_load_const t0 "$rs1"
  cat <<EOF
        add  t2, t0, t1                # EX->EX forward on t0 required
EOF
  emit_nops 3
  emit_load_expected_into_t3 "$exp_s" "$exp_hex"
  cat <<EOF
        beq  t2, t3, ${next}
        jal  x0, Fail_${upper}_${i}

EOF
}

# --- 2b. MEM->EX forwarding (ForwardAE/BE = 2'b01) ---
# One instruction separates producer from consumer.
# Without MEM->EX forward, consumer reads stale register file value.
# args: upper i rs1_val rs2_val next
emit_raw_mem_ex_block() {
  local upper="$1" i="$2" rs1="$3" rs2="$4" next="$5"
  read -r exp_s exp_hex < <(rv32_expect_alu "add" "$rs1" "$rs2")
  cat <<EOF
    test${i}:
EOF
  emit_load_const t1 "$rs2"
  emit_nops 3
  # Produce t0; one intervening real instruction before consumer
  emit_load_const t0 "$rs1"
  cat <<EOF
        addi x0, x0, 0                 # 1 intervening instr (not dependent)
        add  t2, t0, t1                # MEM->EX forward on t0 required
EOF
  emit_nops 3
  emit_load_expected_into_t3 "$exp_s" "$exp_hex"
  cat <<EOF
        beq  t2, t3, ${next}
        jal  x0, Fail_${upper}_${i}

EOF
}

# --- 2c. Load-use stall ---
# lw immediately followed by use of loaded register.
# Hazard unit must insert 1-cycle bubble (stall IF/ID, flush EX).
# Without stall, consumer reads old register file value instead of loaded data.
# args: upper i val next
emit_load_use_block() {
  local upper="$1" i="$2" val="$3" next="$4"
  read -r val_s _ < <(python3 - "$val" <<'PY'
import sys; x=int(sys.argv[1],0); u=x&0xFFFFFFFF
print(u if u<0x80000000 else u-0x100000000, f"0x{u:08x}")
PY
)
  cat <<EOF
    test${i}:
        addi sp, sp, -4
EOF
  emit_load_const t0 "$val_s"
  cat <<EOF
        sw   t0, 0(sp)
        lw   t1, 0(sp)                 # load
        add  t2, t1, x0               # immediate use — load-use stall required
EOF
  emit_nops 3
  emit_load_expected_into_t3 "$val_s" ""
  cat <<EOF
        beq  t2, t3, ${next}
        jal  x0, Fail_${upper}_${i}
        addi sp, sp, 4

EOF
}

# --- 2d. Control hazard — branch flush ---
# Always-taken branch; the two instructions fetched speculatively
# after the branch (in IF and ID when branch resolves in EX) must be
# flushed. Without flush, those instructions corrupt t3.
# Branch resolved in EX => 2-cycle penalty; 2 speculative fetches flushed.
# args: upper i next
emit_branch_flush_block() {
  local upper="$1" i="$2" next="$3"
  cat <<EOF
    test${i}:
        addi t3, x0, 0                # flag = 0
        addi t0, x0, 5
        addi t1, x0, 5
        beq  t0, t1, ${upper}_TAKEN_${i}  # always-taken (5==5)
        addi t3, x0, 99               # speculatively fetched — must be flushed
        addi t3, x0, 99               # speculatively fetched — must be flushed
${upper}_TAKEN_${i}:
        addi t4, x0, 0
        beq  t3, t4, ${next}          # t3 must still be 0
        jal  x0, Fail_${upper}_${i}

EOF
}

# --- 2e. WAW (Write-After-Write) ---
# Two consecutive writes to same register; second write must win.
# In-order pipeline: second write always arrives later so this
# should pass even without special WAW logic — useful sanity check.
# args: upper i val_a val_b next
emit_waw_block() {
  local upper="$1" i="$2" val_a="$3" val_b="$4" next="$5"
  read -r vb_s _ < <(python3 - "$val_b" <<'PY'
import sys; x=int(sys.argv[1],0); u=x&0xFFFFFFFF
print(u if u<0x80000000 else u-0x100000000, f"0x{u:08x}")
PY
)
  cat <<EOF
    test${i}:
EOF
  emit_load_const t2 "$val_a"
  emit_load_const t2 "$val_b"   # second write — must be the survivor
  emit_nops 3
  emit_load_expected_into_t3 "$vb_s" ""
  cat <<EOF
        beq  t2, t3, ${next}
        jal  x0, Fail_${upper}_${i}

EOF
}

# --- 2f. WAR (Write-After-Read) ---
# Instruction reads t0, then t0 is overwritten. The reading
# instruction must see the original value; the write must not
# corrupt the earlier read's result in t2.
# args: upper i orig_val new_val next
emit_war_block() {
  local upper="$1" i="$2" orig="$3" newval="$4" next="$5"
  read -r orig_s _ < <(python3 - "$orig" <<'PY'
import sys; x=int(sys.argv[1],0); u=x&0xFFFFFFFF
print(u if u<0x80000000 else u-0x100000000, f"0x{u:08x}")
PY
)
  cat <<EOF
    test${i}:
EOF
  emit_load_const t0 "$orig_s"
  emit_nops 3
  cat <<EOF
        add  t2, t0, x0              # read t0 into t2
EOF
  emit_load_const t0 "$newval"        # overwrite t0 — must not affect t2
  emit_nops 3
  emit_load_expected_into_t3 "$orig_s" ""
  cat <<EOF
        beq  t2, t3, ${next}         # t2 must still hold orig value
        jal  x0, Fail_${upper}_${i}

EOF
}

